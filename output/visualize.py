from pathlib import Path

import pandas as pd
import matplotlib.pyplot as plt


# ============================================================
# PROJECT PATHS
# ============================================================

PROJECT_DIR = Path(
    "/content/drive/MyDrive/mamaearth_analytics"
)

OUTPUT_DIR = PROJECT_DIR / "output"

VISUALIZATIONS_DIR = PROJECT_DIR / "visualizations"

VISUALIZATIONS_DIR.mkdir(
    parents=True,
    exist_ok=True
)


# ============================================================
# LOAD RESULTS GENERATED BY clean_and_eda.py
# ============================================================

return_rates = pd.read_csv(
    OUTPUT_DIR / "return_rate_by_payment.csv",
    index_col=0
)

monthly_revenue = pd.read_csv(
    OUTPUT_DIR / "monthly_revenue_corrected.csv",
    index_col=0
)

# Ensure the values are numeric.
return_rates["return_rate_pct"] = pd.to_numeric(
    return_rates["return_rate_pct"],
    errors="raise"
)

monthly_revenue["monthly_order_value"] = pd.to_numeric(
    monthly_revenue["monthly_order_value"],
    errors="raise"
)

print("\nLoaded return-rate results:")
print(return_rates)

print("\nLoaded outlier-corrected monthly revenue:")
print(monthly_revenue)


# ============================================================
# CHART 1: RETURN RATE BY PAYMENT METHOD
# ============================================================

print("\nCreating return-rate bar chart...")

# Arrange bars from highest return rate to lowest.
return_rates = return_rates.sort_values(
    "return_rate_pct",
    ascending=False
)

plt.figure(figsize=(8, 5))

bars = plt.bar(
    return_rates.index,
    return_rates["return_rate_pct"]
)

# Display the exact percentage on each bar.
for bar, value in zip(
    bars,
    return_rates["return_rate_pct"]
):
    plt.text(
        bar.get_x() + bar.get_width() / 2,
        bar.get_height(),
        f"{value:.1f}%",
        ha="center",
        va="bottom"
    )

plt.title("COD Returns at 44.4% — 3x Card")

plt.xlabel("Payment Method")

plt.ylabel("Return Rate (%)")

plt.ylim(
    0,
    max(return_rates["return_rate_pct"]) * 1.2
)

plt.tight_layout()

return_chart_path = (
    VISUALIZATIONS_DIR
    / "return_rate_by_payment.png"
)

plt.savefig(
    return_chart_path,
    dpi=300,
    bbox_inches="tight"
)

plt.show()

plt.close()

print("Saved:", return_chart_path)


# ============================================================
# CHART 2: OUTLIER-CORRECTED MONTHLY REVENUE
# ============================================================

print("\nCreating outlier-corrected monthly revenue chart...")

monthly_revenue = monthly_revenue.sort_index()

peak_month = (
    monthly_revenue["monthly_order_value"]
    .idxmax()
)

peak_value = (
    monthly_revenue["monthly_order_value"]
    .max()
)

plt.figure(figsize=(10, 5))

plt.plot(
    monthly_revenue.index,
    monthly_revenue["monthly_order_value"],
    marker="o"
)

plt.title(
    f"Monthly Revenue Trend — Actual Peak: {peak_month}"
)

plt.xlabel("Month")

plt.ylabel("Order Value (INR)")

plt.xticks(
    rotation=45
)

plt.tight_layout()

monthly_chart_path = (
    VISUALIZATIONS_DIR
    / "monthly_revenue_trend.png"
)

plt.savefig(
    monthly_chart_path,
    dpi=300,
    bbox_inches="tight"
)

plt.show()

plt.close()

print("Saved:", monthly_chart_path)

print("\nActual peak month:", peak_month)

print(
    "Peak monthly order value: "
    f"₹{peak_value:,.2f}"
)

print("\n" + "=" * 70)
print("TASK 11 COMPLETED")
print("=" * 70)

print("\nGenerated visualizations:")

print(return_chart_path)

print(monthly_chart_path)
